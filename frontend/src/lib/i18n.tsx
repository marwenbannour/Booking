const DICTS: Record<Lang, Dict> = { fr: FR, ar: AR };

interface I18nState {
  lang: Lang;
  dir: "ltr" | "rtl";
  t: (key: string) => string;
  setLang: (lang: Lang) => void;
}

const I18nContext = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    let stored: Lang | null = null;
    try {
      stored = localStorage.getItem(KEY) as Lang | null;
    } catch {
      /* ignore */
    }
    if (stored === "fr" || stored === "ar") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: string) => DICTS[lang][key] ?? DICTS.fr[key] ?? key,
    [lang],
  );

  const value: I18nState = {
    lang,
    dir: lang === "ar" ? "rtl" : "ltr",
    t,
    setLang,
  };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n doit être utilisé dans un <I18nProvider>");
  return ctx;
}

export function LanguageToggle() {
  const { lang, setLang } = useI18n();
  return (
    <button
      type="button"
      className="btn-quiet"
      onClick={() => setLang(lang === "fr" ? "ar" : "fr")}
    >
      {lang === "fr" ? "العربية" : "Français"}
    </button>
  );
}
